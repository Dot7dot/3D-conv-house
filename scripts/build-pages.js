'use strict';

/**
 * Builds the static GitHub Pages version of 3D-conv-house into a folder
 * (default: _site). Converter URLs come from converters.json and can be
 * overridden with CONVERTER_<ID>_URL (the Pages workflow passes repo variables).
 *
 *   node scripts/build-pages.js [outDir]
 */

const fs = require('node:fs');
const path = require('node:path');
const { loadRegistry } = require('../src/app');

const root = path.join(__dirname, '..');
const out = path.resolve(process.argv[2] || path.join(root, '_site'));

const converters = loadRegistry({ file: path.join(root, 'converters.json') })
  .map(({ id, name, icon, repo, url, path: p }) => ({ id, name, icon, repo, url, path: p }));

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(root, 'public'), out, { recursive: true });
fs.mkdirSync(path.join(out, 'vendor'), { recursive: true });
fs.copyFileSync(
  require.resolve('@google/model-viewer/dist/model-viewer.min.js'),
  path.join(out, 'vendor', 'model-viewer.min.js'),
);
fs.writeFileSync(
  path.join(out, 'config.js'),
  `// Generated by scripts/build-pages.js\nwindow.CONV_HOUSE = ${JSON.stringify({ mode: 'static', converters }, null, 2)};\n`,
);
fs.writeFileSync(path.join(out, '.nojekyll'), '');

console.log(`Built ${out}`);
for (const c of converters) console.log(`  ${c.icon} ${c.name}: ${c.url || '尚未上線'}`);
